-- Week 8 Day 6 | 02 Virtual Warehouse
-- Requires CREATE WAREHOUSE privilege. Compute charges apply when running.
-- XSMALL + auto-suspend helps reduce idle compute costs.

CREATE WAREHOUSE IF NOT EXISTS DE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE DE_WH;
USE DATABASE DE_PROJECT;
USE SCHEMA BRONZE;

SELECT CURRENT_ROLE() AS ROLE_NAME,
       CURRENT_WAREHOUSE() AS WAREHOUSE_NAME,
       CURRENT_DATABASE() AS DATABASE_NAME,
       CURRENT_SCHEMA() AS SCHEMA_NAME,
       CURRENT_REGION() AS REGION;

SHOW WAREHOUSES LIKE 'DE_WH';
