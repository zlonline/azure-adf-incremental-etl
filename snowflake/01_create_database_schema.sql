-- Week 8 Day 6 | 01 Database and Schemas
-- Run first. Requires a role with CREATE DATABASE privileges.
-- Snowflake SQL files can be executed in Workspaces > SQL file.

CREATE DATABASE IF NOT EXISTS DE_PROJECT;
CREATE SCHEMA IF NOT EXISTS DE_PROJECT.BRONZE;
CREATE SCHEMA IF NOT EXISTS DE_PROJECT.SILVER;
CREATE SCHEMA IF NOT EXISTS DE_PROJECT.GOLD;

-- Verification
SHOW DATABASES LIKE 'DE_PROJECT';
SHOW SCHEMAS IN DATABASE DE_PROJECT;
