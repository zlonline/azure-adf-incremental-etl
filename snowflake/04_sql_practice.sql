USE WAREHOUSE DE_WH;
USE DATABASE DE_PROJECT;
USE SCHEMA BRONZE;

CREATE OR REPLACE TEMPORARY TABLE DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE (
  CUSTOMER_ID INT,
  NAME VARCHAR(100),
  EMAIL VARCHAR(200),
  CITY VARCHAR(100),
  UPDATED_AT TIMESTAMP_NTZ
);

