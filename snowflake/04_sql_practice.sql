-- SELECT and WHERE
SELECT * FROM DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE;
SELECT CUSTOMER_ID, NAME, CITY
FROM DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE
WHERE CITY = 'Toronto';

-- GROUP BY
SELECT CITY, COUNT(*) AS CUSTOMER_COUNT
FROM DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE
GROUP BY CITY
ORDER BY CUSTOMER_COUNT DESC, CITY;

-- Date functions
SELECT CUSTOMER_ID, NAME, UPDATED_AT,
       YEAR(UPDATED_AT) AS UPDATE_YEAR,
       MONTH(UPDATED_AT) AS UPDATE_MONTH,
       DAY(UPDATED_AT) AS UPDATE_DAY
FROM DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE;

CREATE OR REPLACE TEMPORARY TABLE DE_PROJECT.BRONZE.ORDERS_SQL_PRACTICE (
  ORDER_ID INT,
  CUSTOMER_ID INT,
  AMOUNT NUMBER(10,2)
);
INSERT INTO DE_PROJECT.BRONZE.ORDERS_SQL_PRACTICE VALUES
  (101, 1, 120.50),
  (102, 1, 80.00),
  (103, 2, 200.00),
  (104, 3, 50.00);

-- LEFT JOIN + aggregation
SELECT C.CUSTOMER_ID, C.NAME,
       COUNT(O.ORDER_ID) AS ORDER_COUNT,
       COALESCE(SUM(O.AMOUNT), 0) AS TOTAL_SALES
FROM DE_PROJECT.BRONZE.CUSTOMERS_SQL_PRACTICE C
LEFT JOIN DE_PROJECT.BRONZE.ORDERS_SQL_PRACTICE O
  ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.NAME
ORDER BY TOTAL_SALES DESC;
