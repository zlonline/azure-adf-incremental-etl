-- Week 8 Day 6 | 03 Target table for COPY INTO
-- Run 01 and 02 first.
-- TIMESTAMP_NTZ has no timezone; treat sample timestamps consistently.
-- This is a sample Snowflake table, not an exact mirror of dbo.customers.

USE WAREHOUSE DE_WH;
USE DATABASE DE_PROJECT;
USE SCHEMA BRONZE;

CREATE TABLE IF NOT EXISTS DE_PROJECT.BRONZE.CUSTOMERS (
  CUSTOMER_ID INT,
  NAME VARCHAR(100),
  EMAIL VARCHAR(200),
  CITY VARCHAR(100),
  UPDATED_AT TIMESTAMP_NTZ
);

DESCRIBE TABLE DE_PROJECT.BRONZE.CUSTOMERS;
SHOW TABLES IN SCHEMA DE_PROJECT.BRONZE;
SELECT COUNT(*) AS TOTAL_ROWS FROM DE_PROJECT.BRONZE.CUSTOMERS;
